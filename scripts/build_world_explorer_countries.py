def validate(countries):
    if len(countries) != 195:
        raise SystemExit(f"expected 195 countries, got {len(countries)}")
    ids = [c["id"] for c in countries]
    if len(set(ids)) != 195:
        dups = sorted({i for i in ids if ids.count(i) > 1})
        raise SystemExit(f"duplicate ids: {dups}")
    idset = set(ids)
    banned = {"tw", "xk"}
    if banned & idset:
        raise SystemExit(f"must not include {banned & idset}")
    for need in ("va", "ps", "cz", "kp", "kr", "cd", "cg", "ci", "sz", "tr", "tl", "md", "gb", "us"):
        if need not in idset:
            raise SystemExit(f"missing required id {need}")
    hist = {k: 0 for k in CONTINENTS}
    for c in countries:
        for key in ("id", "isoCode", "name", "officialName", "nameEn", "officialNameEn",
                    "flag", "capital", "capitalEn", "continent", "region", "subRegion",
                    "currency", "geo", "landscape"):
            if not c.get(key):
                raise SystemExit(f"missing {key} on {c.get('id')}")
        if c["continent"] not in hist:
            raise SystemExit(f"bad continent {c['continent']} on {c['id']}")
        hist[c["continent"]] += 1
        if not c["languages"] or not c["flagColors"] or len(c["facts"]) < 4:
            raise SystemExit(f"bad lists/facts on {c['id']}")
        fids = [f["id"] for f in c["facts"]]
        if len(set(fids)) != len(fids):
            raise SystemExit(f"dup fact ids on {c['id']}")
        for n in c["neighbors"]:
            if n not in idset:
                raise SystemExit(f"{c['id']} neighbor {n} not in library")
        if c["id"] == "ps" and (c["name"] != "Palestine" or c["capital"] != "Ramallah"):
            raise SystemExit("Palestine name/capital contract")
        if c["id"] == "va" and (c["name"] != "Tòa Thánh" or c["capital"] != "Thành Vatican"):
            raise SystemExit("Holy See name/capital contract")
        if c["id"] == "cz" and c["name"] != "Séc":
            raise SystemExit("Czechia must be named Séc")
    return hist


def write_js(countries):
    payload = json.dumps(countries, ensure_ascii=False, indent=2)
    text = (
        "const WorldExplorerLib = (function () {\n"
        "  function flagOf(iso) {\n"
        "    return String(iso).toUpperCase().replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));\n"
        "  }\n"
        "  const CONTINENTS = "
        + json.dumps(CONTINENTS)
        + ";\n"
        "  const COUNTRIES = "
        + payload
        + ";\n"
        "  const INDEX = {};\n"
        "  COUNTRIES.forEach((c) => { INDEX[c.id] = c; });\n"
        "  function all() { return COUNTRIES.slice(); }\n"
        "  function byId(id) { return INDEX[id] || null; }\n"
        "  return { all, byId, TOTAL: COUNTRIES.length, CONTINENTS };\n"
        "})();\n"
        "if (typeof module !== 'undefined') module.exports = { WorldExplorerLib };\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")


def main():
    seen = []
    isos = []
    for raw in RAW:
        iso = raw["iso"].upper()
        if iso in isos:
            raise SystemExit(f"duplicate raw iso {iso}")
        isos.append(iso)
        seen.append(raw)
    if "TW" in isos or "XK" in isos:
        raise SystemExit("Taiwan/Kosovo must not be included")
    all_capitals = [r["capital"] for r in seen]
    countries = [enrich(r, all_capitals) for r in seen]
    hist = validate(countries)
    write_js(countries)
    print(f"Wrote {len(countries)} countries -> {OUT}")
    print("Continent histogram:")
    for key in CONTINENTS:
        print(f"  {key}: {hist[key]}")


if __name__ == "__main__":
    main()
