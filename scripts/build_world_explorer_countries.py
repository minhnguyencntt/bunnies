def flag_of(iso):
    return "".join(chr(127397 + ord(c)) for c in iso.upper())


def slug(text):
    out = []
    for ch in (text or "").lower():
        if ch.isalnum():
            out.append(ch)
        elif ch in " -_'":
            out.append("-")
    s = "".join(out).strip("-")
    while "--" in s:
        s = s.replace("--", "-")
    return s or "x"


def capital_wrongs(country, all_capitals):
    wrongs = []
    seen = {country["capital"]}
    for city in country.get("altCities") or []:
        if city and city not in seen:
            wrongs.append(city)
            seen.add(city)
    for city in PAD_CITIES:
        if city not in seen:
            wrongs.append(city)
            seen.add(city)
        if len(wrongs) >= 3:
            break
    return wrongs[:3]


